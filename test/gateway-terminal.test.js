import { test } from 'node:test'
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import path from 'node:path'

const require = createRequire(import.meta.url)
const gateway = require('../lib/gateway-terminal.cjs')
const child = require('../lib/remote-shell-child.cjs')

const TARGET = { host: 'bastion.example', port: 2200, username: 'root', remotePath: '/srv/project' }
const MACHINE = { useSshConfig: true, host: 'gateway' }

// ── probe interpretation ───────────────────────────────────────────────────

test('a real tty in the probe answer means exec requests get a pty', () => {
  assert.equal(gateway.execPtyAvailable('DSH_EXEC_PTY_/dev/pts/21'), true)
  assert.equal(gateway.execPtyAvailable('DSH_EXEC_PTY_/dev/ttys003'), true)
  assert.equal(gateway.execPtyAvailable('junk\nDSH_EXEC_PTY_/dev/pts/0\r\n'), true)
})

test('not-a-tty, missing marker or unrelated output means no exec pty', () => {
  assert.equal(gateway.execPtyAvailable('DSH_EXEC_PTY_not a tty'), false)
  assert.equal(gateway.execPtyAvailable('/dev/pts/3 but no marker'), false)
  assert.equal(gateway.execPtyAvailable(''), false)
  assert.equal(gateway.execPtyAvailable(undefined), false)
})

test('probeExecPty treats spawn failure as no exec pty and never throws', () => {
  const calls = []
  const ok = gateway.probeExecPty('ssh', ['-tt', 'h', 'cmd'], {}, {
    spawnSync: (bin, args) => {
      calls.push([bin, args])
      return { stdout: 'DSH_EXEC_PTY_/dev/pts/9', stderr: '' }
    },
  })
  assert.equal(ok, true)
  assert.equal(calls[0][0], 'ssh')
  assert.equal(gateway.probeExecPty('ssh', [], {}, {
    spawnSync: () => { throw new Error('ENOENT') },
  }), false)
})

// ── expect discovery ───────────────────────────────────────────────────────

test('expect is found on POSIX and never on Windows', () => {
  // Build the expected path with path.join: the path module uses the host's
  // separator (\\ on Windows), so a hardcoded '/opt/bin/expect' would not match.
  const expectPath = path.join('/opt/bin', 'expect')
  assert.equal(gateway.findExpect({ PATH: '/opt/bin' }, (p) => p === expectPath, 'darwin'), expectPath)
  assert.equal(gateway.findExpect({}, () => false, 'darwin'), undefined)
  assert.equal(gateway.findExpect({ PATH: '/bin' }, () => true, 'win32'), undefined)
})

// ── generated expect program ───────────────────────────────────────────────

test('the gateway script waits for the line editor, types cd, then goes interactive', () => {
  const src = gateway.gatewayExpectScript()
  assert.match(src, /spawn \{?\*\}/, 'ssh is spawned as one argv list, never eval-ed')
  assert.match(src, /send -- "\$cdCmd\\r"/, 'the cd is typed with a real Return')
  assert.match(src, /interact/, 'user input is handed over untouched after login')
  assert.match(src, /SIGWINCH/, 'window size is forwarded')
  assert.match(src, /stty -f \$dev/, 'resize goes through the kernel, not escape keys')
  assert.match(src, /re \{\\x1b\\\[\\\?2004h\}/, 'bracketed paste marks the ready prompt')
})

test('the temp expect script is private, written once and removed on exit', () => {
  const written = []
  let cleanup
  const file = gateway.writeGatewayExpectScript({
    tmpdir: '/tmp/dsh-test', pid: 42, now: 7,
    writeFile: (p, content, opts) => written.push([p, content, opts]),
    unlink: (p) => written.push(['unlink', p]),
    onExit: (fn) => { cleanup = fn },
  })
  assert.equal(file, path.join('/tmp/dsh-test', 'dsh-remote-gateway-42-7.exp'))
  assert.equal(written.length, 1)
  assert.equal(written[0][2].mode, 0o700)
  assert.match(written[0][1], /^# Generated by dsh-remote/)
  cleanup()
  assert.deepEqual(written[1], ['unlink', file])
})

// ── the cd typed into the gateway session ──────────────────────────────────

test('the gateway cd keeps ~ remote and quotes hostile path characters', () => {
  assert.equal(child.gatewayCdCommand(''), 'cd -- "$HOME" 2>/dev/null || cd -- "$HOME"')
  assert.equal(child.gatewayCdCommand('~/proj'), 'cd -- "$HOME"/\'proj\' 2>/dev/null || cd -- "$HOME"')
  assert.equal(child.gatewayCdCommand("/srv/it's"), 'cd -- \'/srv/it\'\\\'\'s\' 2>/dev/null || cd -- "$HOME"')
  assert.equal(child.gatewayCdCommand('-weird'), 'cd -- \'-weird\' 2>/dev/null || cd -- "$HOME"')
})

// ── adaptive launch ────────────────────────────────────────────────────────

test('gatewayHandover skips Windows paths and hosts without expect', () => {
  const calls = []
  const deps = {
    platform: 'darwin', // force the POSIX code path regardless of the CI runner
    findExpect: () => '/usr/bin/expect',
    handover: (...args) => { calls.push(args); return 'child' },
    probeExecPty: () => false,
  }
  assert.equal(child.gatewayHandover('ssh', { ...TARGET, remotePath: 'D:\\Code' }, MACHINE, undefined, deps), undefined)
  assert.equal(calls.length, 0)
  assert.equal(child.gatewayHandover('ssh', TARGET, MACHINE, undefined, {
    ...deps, findExpect: () => undefined,
  }), undefined)
  assert.equal(calls.length, 0)
})

test('a normal sshd (exec pty available) keeps the direct ssh path', () => {
  const calls = []
  const result = child.gatewayHandover('ssh', TARGET, MACHINE, undefined, {
    findExpect: () => '/usr/bin/expect',
    probeExecPty: () => true,
    handover: () => { throw new Error('must not launch expect') },
    writeGatewayExpectScript: () => { throw new Error('must not write a script') },
  })
  assert.equal(result, undefined)
  assert.equal(calls.length, 0)
})

test('a gateway without exec pty is driven by expect: no command + typed cd', () => {
  let launch
  const result = child.gatewayHandover('/usr/bin/ssh', TARGET, MACHINE, undefined, {
    platform: 'darwin', // force the POSIX code path regardless of the CI runner
    findExpect: () => '/usr/bin/expect',
    probeExecPty: () => false,
    writeGatewayExpectScript: () => '/tmp/gateway.exp',
    handover: (...args) => { launch = args; return 'child' },
  })
  assert.equal(result, 'child')
  assert.equal(launch[0], '/usr/bin/expect')
  assert.deepEqual(launch[1], ['/tmp/gateway.exp', child.gatewayCdCommand(TARGET.remotePath), '/usr/bin/ssh', '-tt', 'gateway'])
})

test('connect args are shared by the probe, direct path and expect path', () => {
  assert.deepEqual(child.buildSshConnectArgs(TARGET, MACHINE), ['-tt', 'gateway'])
  assert.deepEqual(child.buildSshConnectArgs(TARGET, { privateKeyPath: '/k', port: 2201 }), ['-tt', '-p', '2200', '-i', '/k', 'root@bastion.example'])
  const direct = child.buildSshArgs(TARGET, MACHINE)
  assert.deepEqual(direct, ['-tt', 'gateway', child.remoteCommand(TARGET.remotePath)])
})

// ── the reported scenario, end to end ──────────────────────────────────────

test('a relay that denies a pty to exec requests gets a no-command login + typed cd', () => {
  // A JumpServer-style relay answers the probe with "not a tty" even under -tt.
  const probeAnswer = 'DSH_EXEC_PTY_not a tty'
  assert.equal(gateway.execPtyAvailable(probeAnswer), false)

  let launch
  let scriptFile
  const probeBin = '/usr/bin/ssh'
  const probeArgs = child.buildSshConnectArgs(TARGET, MACHINE)
    .concat(gateway.EXEC_PTY_PROBE_COMMAND)

  const result = child.gatewayHandover(probeBin, TARGET, MACHINE, undefined, {
    platform: 'darwin', // force the POSIX code path regardless of the CI runner
    findExpect: () => '/usr/bin/expect',
    // The real probeExecPty would run probeArgs; feed it the relay's answer.
    probeExecPty: (ssh, args) => {
      assert.equal(ssh, probeBin)
      assert.deepEqual(args, probeArgs)
      return gateway.execPtyAvailable(probeAnswer)
    },
    writeGatewayExpectScript: () => { scriptFile = '/tmp/gateway.exp'; return scriptFile },
    handover: (...args) => { launch = args; return 'child' },
  })

  // 1. The gateway route was actually taken.
  assert.equal(result, 'child')
  assert.equal(launch[0], '/usr/bin/expect')

  // 2. ssh is launched with NO remote command: only the connection arguments.
  //    This is what makes the relay allocate a real pty (the root cause fix).
  assert.equal(launch[1][2], probeBin, 'ssh itself is spawned by expect, not passed as an exec command')
  const sshArgv = launch[1].slice(3)
  assert.deepEqual(sshArgv, ['-tt', 'gateway'])
  assert.equal(sshArgv.includes(child.remoteCommand(TARGET.remotePath)), false)

  // 3. The workspace cd is typed into that pty as an argument to the expect
  //    program — not smuggled into ssh as an exec command.
  assert.equal(launch[1][1], child.gatewayCdCommand(TARGET.remotePath))
  assert.match(launch[1][1], /^cd -- /)

  // 4. The regression: no script(1) wrapper. It used to create a second pty,
  //    so zsh's ZLE redraws overlapped and `ls` rendered as `lls`.
  const wholeLaunch = launch[1].join(' ')
  assert.equal(/script\s+-q\s+-c/.test(wholeLaunch), false)

  // 5. Resize goes to the child pty through the kernel, never as escape keys
  //    that a relay would mistake for typing and abort the login.
  const script = gateway.gatewayExpectScript()
  assert.match(script, /stty -f \$dev rows \$rows cols \$cols/)
  assert.equal(/send .*\\x1b\[8;/.test(script), false)
})
