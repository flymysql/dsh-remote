#!/usr/bin/env node
/**
 * Gateway-compatible terminal launch for dsh-remote.
 *
 * Some SSH relays (JumpServer and descendants) refuse to allocate a remote PTY
 * when the client sends a command with the connection. `ssh -tt` is not enough:
 * the relay still starts the command with stdin/stdout/stderr attached to pipes.
 * The remote shell then has no line discipline, so the terminal emits no ICRNL
 * translation — Return (`\r`) is swallowed, bracketed paste never starts, and
 * readline/zsh reprints prompts on top of each other. From the user's side the
 * terminal looks alive but every key stroke is ignored or duplicated.
 *
 * The workaround is to log in with **no command** (which makes even these relays
 * allocate a real PTY) and type the workspace `cd` into that PTY after login.
 * We only need this for gateways with the limitation; ordinary sshd allocates a
 * PTY for exec requests too, so they keep the historical, dependency-free path.
 *
 * This file is plain CommonJS on purpose: `remote-shell-child.cjs` is spawned as
 * a standalone script by the generated launcher and cannot import ESM.
 */

'use strict'

const { spawnSync } = require('node:child_process')
const { writeFileSync, unlinkSync } = require('node:fs')
const os = require('node:os')
const path = require('node:path')

/** Printed by the probe command so its own tty answer can be recognised. */
const EXEC_PTY_MARKER = 'DSH_EXEC_PTY_'
/** A shell command that reports whether the exec channel has a real tty. */
const EXEC_PTY_PROBE_COMMAND = 'printf ' + EXEC_PTY_MARKER + '; tty'

/**
 * Read the probe answer. A real pty is reported as /dev/pts/N (Linux) or
 * /dev/ttysNNN (macOS); a gateway without exec-PTY answers "not a tty".
 *
 * Pure so it can be unit tested without opening a connection.
 *
 * @param {string} output - combined stdout/stderr of the probe connection
 * @returns {boolean}
 */
function execPtyAvailable(output) {
  const text = String(output || '')
  if (!text.includes(EXEC_PTY_MARKER)) return false
  return /\/dev\/(?:pts|tty)[^\s\r\n]*/.test(text)
}

/**
 * Look for an `expect` interpreter. macOS ships it; most Linux distributions
 * have it in /usr/bin. Windows uses the historical path and never calls this.
 *
 * @param {object} [env]
 * @param {(p: string) => boolean} [exists]
 * @param {string} [platform]
 * @returns {string | undefined}
 */
function findExpect(env = process.env, exists = (p) => {
  try {
    // eslint-disable-next-line no-undef
    require('node:fs').accessSync(p, require('node:fs').constants.X_OK)
    return true
  } catch {
    return false
  }
}, platform = process.platform) {
  if (platform === 'win32') return undefined
  const seen = new Set()
  const dirs = ['/usr/bin', '/bin', '/usr/local/bin']
  for (const dir of String(env.PATH || '').split(path.delimiter)) if (dir) dirs.push(dir)
  for (const dir of dirs) {
    if (seen.has(dir)) continue
    seen.add(dir)
    const candidate = path.join(dir, 'expect')
    if (exists(candidate)) return candidate
  }
  return undefined
}

/**
 * The expect program that drives the no-command login.
 *
 * `log_user 1` forwards the ssh session to the terminal unchanged. Prompt
 * detection uses bracketed paste (`\x1b[?2004h`), which zsh and modern bash emit
 * when their line editor is ready; a timeout still sends the cd so a shell
 * without bracketed paste is not stranded. After the second prompt the session
 * is handed over with `interact` — no more interception of user input.
 *
 * SIGWINCH must not send escape sequences to ssh: a gateway treats them as keys
 * and aborts the login. Instead we resize the child pty with `stty -f`, which
 * ssh notices through the kernel. Until login is complete the trap is a no-op.
 *
 * @returns {string} expect program source (LF terminated)
 */
function gatewayExpectScript() {
  return [
    '# Generated by dsh-remote — do not edit.',
    'set timeout 90',
    'set cdCmd [lindex $argv 0]',
    'set ready 0',
    'log_user 1',
    '',
    'trap {',
    '    if {!$ready} { return }',
    '    catch {',
    '        set sz [exec /bin/stty size < /dev/tty]',
    '        set rows [lindex $sz 0]',
    '        set cols [lindex $sz 1]',
    '        set tty [exec /bin/ps -o tty= -p [exp_pid]]',
    '        set dev "/dev/[string trim $tty]"',
    '        exec /bin/stty -f $dev rows $rows cols $cols',
    '    }',
    '} SIGWINCH',
    '',
    'spawn {*}[lrange $argv 1 end]',
    'expect {',
    '    -re {\\x1b\\[\\?2004h} { }',
    '    timeout { }',
    '}',
    'send -- "$cdCmd\\r"',
    'expect {',
    '    -re {\\x1b\\[\\?2004h} { }',
    '    timeout { }',
    '}',
    'set ready 1',
    'interact',
    '',
  ].join('\n')
}

/**
 * Materialise the expect program in a private temp file and remove it when the
 * child process exits. The file is generated, contains no secrets, and is only
 * needed until `expect` has read it.
 *
 * @param {{ tmpdir?: string, pid?: number, now?: number,
 *           writeFile?: Function, unlink?: Function, onExit?: Function }} [deps]
 * @returns {string} absolute path of the written file
 */
function writeGatewayExpectScript(deps = {}) {
  const dir = deps.tmpdir || os.tmpdir()
  const pid = deps.pid == null ? process.pid : deps.pid
  const now = deps.now == null ? Date.now() : deps.now
  const file = path.join(dir, `dsh-remote-gateway-${pid}-${now}.exp`)
  const write = deps.writeFile || writeFileSync
  const unlink = deps.unlink || unlinkSync
  write(file, gatewayExpectScript(), { mode: 0o700 })
  const cleanup = () => { try { unlink(file) } catch { /* already gone */ } }
  if (deps.onExit) deps.onExit(cleanup)
  else process.once('exit', cleanup)
  return file
}

/**
 * Run the short probe connection and report whether exec requests get a pty.
 *
 * Never throws: any auth failure, timeout or missing binary is treated as "no
 * exec pty", which routes to the gateway path — the no-command login is the
 * safer default because it always allocates a pty on both ordinary and gated
 * servers.
 *
 * @param {string} ssh - ssh binary
 * @param {string[]} args - full argument list including the probe command
 * @param {object} env - environment for ssh (includes the askpass bridge if any)
 * @param {{ spawnSync?: Function, timeout?: number }} [deps]
 * @returns {boolean}
 */
function probeExecPty(ssh, args, env, deps = {}) {
  const run = deps.spawnSync || spawnSync
  let result
  try {
    result = run(ssh, args, {
      env,
      encoding: 'utf8',
      timeout: deps.timeout || 12000,
      stdio: ['ignore', 'pipe', 'pipe'],
    })
  } catch {
    return false
  }
  const output = `${(result && result.stdout) || ''}${(result && result.stderr) || ''}`
  return !result.error && execPtyAvailable(output)
}

module.exports = {
  EXEC_PTY_MARKER,
  EXEC_PTY_PROBE_COMMAND,
  execPtyAvailable,
  findExpect,
  gatewayExpectScript,
  probeExecPty,
  writeGatewayExpectScript,
}
